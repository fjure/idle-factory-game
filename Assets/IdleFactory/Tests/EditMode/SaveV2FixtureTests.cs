    /// <summary>
    /// The committed Save V2 fixtures under <c>Assets/IdleFactory/Tests/EditMode/Fixtures/SaveV2/</c> (T104, OPS-5).
    /// Every fixture and the README are regenerated in memory from <see cref="SaveV2Scenarios"/> and compared byte for
    /// byte with the committed files. A difference fails the test and is never skipped; set
    /// <c>IDLEFACTORY_REGENERATE_SAVEV2_FIXTURES=1</c> to rewrite the files (the comparison still runs afterwards,
    /// against the files just written). The README lists each fixture with its scenario and SHA-256 hash.
    /// </summary>
    public sealed class SaveV2FixtureTests
    {
        private const string RegenerateEnvironmentVariable = "IDLEFACTORY_REGENERATE_SAVEV2_FIXTURES";
        private const string RelativeDirectory = "IdleFactory/Tests/EditMode/Fixtures/SaveV2";

        private static bool Regenerate => Environment.GetEnvironmentVariable(RegenerateEnvironmentVariable) == "1";
        private static string Directory_ => Path.Combine(Application.dataPath, RelativeDirectory);

        private bool _logToUnity;

        [SetUp]
        public void SetUp()
        {
            _logToUnity = CheckpointDiagnostics.LogToUnity;
            CheckpointDiagnostics.LogToUnity = false;
        }

        [TearDown]
        public void TearDown()
        {
            CheckpointDiagnostics.LogToUnity = _logToUnity;
        }

        private static string Readme(List<SaveV2Fixture> fixtures)
        {
            var b = new StringBuilder();
            b.Append("# Save V2 fixtures\n\n");
            b.Append("Generated by `SaveV2FixtureTests.CommittedFixtures_AreByteIdenticalToTheirInMemoryRegeneration` (T104) from `SaveV2Scenarios`, ");
            b.Append("the unchanged Core run domain, `W003Workload` and `SaveV2Mapper`. The test regenerates every file and this README in memory and compares ");
            b.Append("them byte for byte with the committed copies. Drift fails the test; it never skips (OPS-5). To regenerate deliberately, set ");
            b.Append("`IDLEFACTORY_REGENERATE_SAVEV2_FIXTURES=1` and run the test file directly:\n\n");
            b.Append("```powershell\n");
            b.Append("$env:IDLEFACTORY_REGENERATE_SAVEV2_FIXTURES='1'; scripts/test-unity.ps1 -TestFile Assets/IdleFactory/Tests/EditMode/SaveV2FixtureTests.cs\n");
            b.Append("```\n\n");
            b.Append("Hashes are SHA-256 over the file bytes. Valid fixtures load and re-serialize to identical bytes. Corrupt fixtures are ");
            b.Append("syntactically valid, structurally complete files that break exactly one cross-field bound of load rule 4 (SEC-2) and are rejected with ");
            b.Append("`" + SaveV2Codes.CrossField + "`.\n\n");
            b.Append("Fixtures 01 to 04 load against the test catalog of `SaveV2Scenarios.Options()` (`RunCommandFixtures`); 05 to 07 load against the ");
            b.Append("test-local catalog of `W003Workload`. ");
            b.Append("plan.md, Performance now carries the event bound on W003-B, so W003-B, W003-S and W003-R are all committed; the contract's fixture list names only S and R, ");
            b.Append("and B is the record that carries the SC-008 event bound. W003-S must not be used as that record.\n\n");
            b.Append("| File | Scenario | SHA-256 |\n|---|---|---|\n");
            foreach (SaveV2Fixture f in fixtures)
                b.Append("| `" + f.FileName + "` | " + f.Scenario + " | `" + SaveV2Scenarios.Sha256(f.Bytes) + "` |\n");
            b.Append(SaveV2DeviceSets.ReadmeSection());
            return b.ToString();
        }

        [Test]
        public void CommittedFixtures_AreByteIdenticalToTheirInMemoryRegeneration()
        {
            List<SaveV2Fixture> fixtures = SaveV2Scenarios.All();
            string readme = Readme(fixtures);
            if (Regenerate)
            {
                Directory.CreateDirectory(Directory_);
                foreach (SaveV2Fixture f in fixtures) File.WriteAllBytes(Path.Combine(Directory_, f.FileName), f.Bytes);
                SaveV2DeviceSets.WriteW003S(Directory_);
                File.WriteAllText(Path.Combine(Directory_, "README.md"), readme, new UTF8Encoding(false));
                AssetDatabase.Refresh();
            }

            string hint = " Set " + RegenerateEnvironmentVariable + "=1 and rerun to update the committed fixtures.";
            foreach (SaveV2Fixture f in fixtures)
            {
                string path = Path.Combine(Directory_, f.FileName);
                Assert.That(File.Exists(path), Is.True, "Committed Save V2 fixture is missing: " + f.FileName + "." + hint);
                Assert.That(File.ReadAllBytes(path), Is.EqualTo(f.Bytes), "Save V2 fixture drifted: " + f.FileName + "." + hint);
            }

            string readmePath = Path.Combine(Directory_, "README.md");
            Assert.That(File.Exists(readmePath), Is.True, "Committed Save V2 fixture README is missing." + hint);
            Assert.That(File.ReadAllText(readmePath, new UTF8Encoding(false)).Replace("\r\n", "\n"), Is.EqualTo(readme),
                "Save V2 fixture README is stale." + hint);

            var expected = new HashSet<string>(fixtures.Select(f => f.FileName), StringComparer.Ordinal);
            foreach (string file in Directory.GetFiles(Directory_, "*.json"))
                Assert.That(expected.Contains(Path.GetFileName(file)), Is.True, "Unlisted Save V2 fixture on disk: " + Path.GetFileName(file));
        }

        [Test]
        public void Readme_ListsEveryFixtureWithItsHash()
        {
            string readme = File.ReadAllText(Path.Combine(Directory_, "README.md"), new UTF8Encoding(false));
            foreach (SaveV2Fixture f in SaveV2Scenarios.All())
            {
                string row = readme.Split('\n').SingleOrDefault(line => line.StartsWith("| `" + f.FileName + "`", StringComparison.Ordinal));
                Assert.That(row, Is.Not.Null, f.FileName);
                Assert.That(row, Does.Contain(SaveV2Scenarios.Sha256(File.ReadAllBytes(Path.Combine(Directory_, f.FileName)))));
            }
        }

        [Test]
        public void ValidFixtures_LoadFromDisk_AndReserializeToIdenticalBytes()
        {
            foreach (SaveV2Fixture f in SaveV2Scenarios.All().Where(x => !x.IsCorrupt))
            {
                byte[] disk = File.ReadAllBytes(Path.Combine(Directory_, f.FileName));
                SaveV2ReadResult read = SaveV2Mapper.Deserialize(disk, f.Catalog);
                Assert.That(read.IsSuccess, Is.True, f.FileName + " " + read.Code);
                Assert.That(SaveV2Scenarios.Dump(read.Document.Run, read.Document.Permanent), Is.EqualTo(SaveV2Scenarios.Dump(f.Run, f.Permanent)), f.FileName);
                Assert.That(read.Document.SchemaVersion, Is.EqualTo(SaveV2Mapper.LegacySchemaVersion), f.FileName);
                SaveV2WriteResult again = SaveV2Mapper.Serialize(read.Document.Meta, read.Document.Run, read.Document.Permanent, SaveV2Mapper.LegacySchemaVersion);
                Assert.That(again.IsSuccess, Is.True, f.FileName);
                Assert.That(again.Bytes, Is.EqualTo(disk), f.FileName);

                // Save V3 (T334): the player writes the loaded V2 state as V3, which reads back to the same state and bytes.
                SaveV2WriteResult upgraded = SaveV2Mapper.Serialize(read.Document.Meta, read.Document.Run, read.Document.Permanent);
                Assert.That(upgraded.IsSuccess, Is.True, f.FileName + " " + upgraded.Code);
                Assert.That(upgraded.Bytes, Is.EqualTo(f.V3Bytes), f.FileName);
                SaveV2ReadResult reread = SaveV2Mapper.Deserialize(upgraded.Bytes, f.Catalog);
                Assert.That(reread.IsSuccess, Is.True, f.FileName + " " + reread.Code);
                Assert.That(reread.Document.SchemaVersion, Is.EqualTo(SaveV2Mapper.SchemaVersion), f.FileName);
                Assert.That(SaveV2Scenarios.Dump(reread.Document.Run, reread.Document.Permanent), Is.EqualTo(SaveV2Scenarios.Dump(f.Run, f.Permanent)), f.FileName);
            }
        }

        [Test]
        public void CorruptFixtures_AreRejectedFromDisk_WithTheirCrossFieldCode()
        {
            List<SaveV2Fixture> corrupt = SaveV2Scenarios.All().Where(x => x.IsCorrupt).ToList();
            Assert.That(corrupt.Count, Is.EqualTo(9));
            foreach (SaveV2Fixture f in corrupt)
            {
                byte[] disk = File.ReadAllBytes(Path.Combine(Directory_, f.FileName));
                SaveV2ReadResult read = SaveV2Mapper.Deserialize(disk, f.Catalog);
                Assert.That(read.IsSuccess, Is.False, f.FileName);
                Assert.That(read.Code, Is.EqualTo(f.ExpectedCode), f.FileName);
            }
        }

        [Test]
        public void W003Fixtures_LoadWithTheirWorkloadShape()
        {
            foreach (string name in new[] { "05-w003-b-bound.json", "06-w003-s-stress.json", "07-w003-r-reference.json" })
            {
                SaveV2Fixture f = SaveV2Scenarios.All().Single(x => x.FileName == name);
                SaveV2ReadResult read = SaveV2Mapper.Deserialize(File.ReadAllBytes(Path.Combine(Directory_, name)), f.Catalog);
                Assert.That(read.IsSuccess, Is.True, name + " " + read.Code);
                RunState run = read.Document.Run;
                Assert.That(run.Machines.Count, Is.EqualTo(12), name);
                Assert.That(run.Machines.Count(m => m.MachineId == "machine.miner"), Is.EqualTo(3), name);
                Assert.That(run.Machines.Count(m => m.MachineId == "machine.smelter"), Is.EqualTo(4), name);
                Assert.That(run.Machines.Count(m => m.MachineId == "machine.press"), Is.EqualTo(3), name);
                Assert.That(run.Machines.Count(m => m.MachineId == "machine.assembler"), Is.EqualTo(2), name);
                Assert.That(run.Effects.Count, Is.EqualTo(1), name);
                Assert.That(run.Overdrive.ActiveUntilUtcMs.HasValue, Is.True, name);
                Assert.That(read.Document.Meta.DepartureUtcMs, Is.EqualTo(W003Workload.StartUtcMs), name);
            }
        }
    }
